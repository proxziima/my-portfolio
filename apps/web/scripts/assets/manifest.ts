import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, relative, sep } from 'node:path'
import { fileURLToPath } from 'node:url'
import { contentHash, sha256 } from './hash.ts'
import { SOURCE_DIR, type Recipe } from './recipes.ts'

export type ManifestValue = string | number | boolean | readonly ManifestValue[] | { readonly [key: string]: ManifestValue }

export interface LockEntry {
  /** sha256 of the source bytes. */
  source: string
  /** sha256 of `JSON.stringify(recipe)`. */
  recipe: string
  /** Encoder versions the outputs were made with. */
  tools: Record<string, string>
  /** `/assets/…` paths are served from `public/`; others are relative to `apps/web`. */
  outputs: string[]
  /**
   * What `ASSETS` holds for this id: the manifest is regenerated from the lock alone. Absent when
   * code never imports the output (the OS fonts: `next/font/local` needs a literal path).
   */
  value?: ManifestValue
  /** The parity numbers each output passed with. */
  parity?: ManifestValue
}

export type Lock = Record<string, LockEntry>

export interface LockProblem {
  /** The recipe id; for `manifest stale` the manifest file, for `orphan` the file's `/assets/…` path. */
  id: string
  problem: 'not built' | 'source changed' | 'recipe changed' | 'output missing' | 'output changed' | 'manifest stale' | 'orphan'
  /** The output concerned, for `output missing` and `output changed`. */
  detail?: string
}

/** What `assets:check` reads from disk, injectable for tests. */
export interface CheckIo {
  exists(output: string): boolean
  readOutput(output: string): Uint8Array
  /** The committed `lib/assets/manifest.ts`. */
  manifest(): string
  /** Every file under `public/assets`, as `/assets/…` paths. */
  publicAssets(): string[]
}

export const WEB_ROOT = fileURLToPath(new URL('../../', import.meta.url))
export const PUBLIC_DIR = join(WEB_ROOT, 'public')
export const LOCK_FILE = join(SOURCE_DIR, 'manifest.lock.json')
export const MANIFEST_FILE = join(WEB_ROOT, 'lib/assets/manifest.ts')

/** Where an output recorded in the lock lives on disk. */
export const outputFile = (output: string): string => (output.startsWith('/') ? join(PUBLIC_DIR, output) : join(WEB_ROOT, output))

export const recipeHash = (recipe: Recipe): string => sha256(JSON.stringify(recipe))

const IDENTIFIER = /^[A-Za-z_$][\w$]*$/

/** A TS literal in the repo's style (single quotes, bare keys, trailing commas), so the generated file reads like code. */
function literal(value: ManifestValue, depth: number): string {
  if (typeof value === 'string') return `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`
  if (typeof value !== 'object') return String(value)
  const pad = '  '.repeat(depth + 1)
  const close = '  '.repeat(depth)
  if (Array.isArray(value)) {
    const items = (value as readonly ManifestValue[]).map((v) => `${pad}${literal(v, depth + 1)},\n`)
    return items.length ? `[\n${items.join('')}${close}]` : '[]'
  }
  const entries = Object.entries(value as Record<string, ManifestValue>).map(
    ([k, v]) => `${pad}${IDENTIFIER.test(k) ? k : literal(k, 0)}: ${literal(v, depth + 1)},\n`,
  )
  return entries.length ? `{\n${entries.join('')}${close}}` : '{}'
}

type Tree = { [key: string]: Tree | ManifestValue }
const LEAF = Symbol('leaf')

/**
 * `lib/assets/manifest.ts` from `id → value`: dotted ids nest. Duplicate ids, and an id that is both
 * a leaf and a branch ('desk.a' and 'desk.a.b'), throw instead of silently dropping an asset.
 */
export function toManifestSource(values: Record<string, ManifestValue> | ReadonlyArray<readonly [string, ManifestValue]>): string {
  const entries = Array.isArray(values) ? values : Object.entries(values)
  const root: Tree = {}
  const leaves = new Set<Tree | ManifestValue>()
  const seen = new Set<string>()
  for (const [id, value] of entries as ReadonlyArray<readonly [string, ManifestValue]>) {
    if (seen.has(id)) throw new Error(`duplicate asset id: ${id}`)
    seen.add(id)
    const parts = id.split('.')
    let node = root
    for (const part of parts.slice(0, -1)) {
      const next = node[part]
      if (next !== undefined && leaves.has(next)) throw new Error(`asset id is both a leaf and a branch: ${id}`)
      node = (node[part] ??= {}) as Tree
    }
    const last = parts.at(-1)!
    if (node[last] !== undefined) throw new Error(`asset id is both a leaf and a branch: ${id}`)
    // wrap so an object value is never mistaken for a branch
    const leaf = { [LEAF]: value } as unknown as Tree
    leaves.add(leaf)
    node[last] = leaf
  }
  const unwrap = (node: Tree): ManifestValue =>
    leaves.has(node) ? (node as unknown as Record<symbol, ManifestValue>)[LEAF]! : Object.fromEntries(Object.entries(node).map(([k, v]) => [k, unwrap(v as Tree)]))
  return [
    '// GENERATED by scripts/assets/build.ts — do not edit. Sources: apps/web/assets-src.',
    "export type { ImageAsset, ImageVariant, TextureAsset, VideoAsset, VideoSource } from './types'",
    '',
    `export const ASSETS = ${literal(unwrap(root), 0)} as const`,
    '',
  ].join('\n')
}

/** `lib/assets/manifest.ts` as the lock defines it: built recipes with a value, in recipe order. */
export function manifestSource(recipes: readonly Recipe[], lock: Lock): string {
  return toManifestSource(recipes.flatMap((r) => (lock[r.id]?.value === undefined ? [] : [[r.id, lock[r.id]!.value!] as const])))
}

/** Writes `lib/assets/manifest.ts` and `assets-src/manifest.lock.json`, both in recipe order. */
export function writeManifest(recipes: readonly Recipe[], lock: Lock): void {
  const built = recipes.filter((r) => lock[r.id])
  writeFileSync(MANIFEST_FILE, manifestSource(recipes, lock))
  const ordered = Object.fromEntries(built.map((r) => [r.id, lock[r.id]]))
  writeFileSync(LOCK_FILE, `${JSON.stringify(ordered, null, 2)}\n`)
}

const ASSETS_DIR = join(PUBLIC_DIR, 'assets')

const walk = (dir: string): string[] =>
  existsSync(dir) ? readdirSync(dir, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(join(dir, e.name)) : [join(dir, e.name)])) : []

/** The real disk. */
export const diskIo: CheckIo = {
  exists: (output) => existsSync(outputFile(output)),
  readOutput: (output) => readFileSync(outputFile(output)),
  manifest: () => readFileSync(MANIFEST_FILE, 'utf8'),
  publicAssets: () => walk(ASSETS_DIR).map((file) => `/${relative(PUBLIC_DIR, file).split(sep).join('/')}`),
}

/** The content hash `hashedName` put in a file name (`name.<10 hex>.<ext>`), or null for an unhashed output. */
const NAME_HASH = /\.([0-9a-f]{10})\.[^./]+$/

/**
 * What `assets:check` reports per recipe: the first reason its committed outputs may not match its
 * source and recipe, or bytes that no longer match the hash in their file name (an output edited or
 * replaced by hand keeps its immutable URL, so every cache would keep the old bytes). Needs no
 * encoders, so CI can run it.
 */
export function checkLock(recipes: readonly Recipe[], lock: Lock, readSource: (source: string) => Uint8Array, io: CheckIo = diskIo): LockProblem[] {
  const problems: LockProblem[] = []
  for (const recipe of recipes) {
    const entry = lock[recipe.id]
    const problem = (p: LockProblem['problem'], detail?: string) => problems.push({ id: recipe.id, problem: p, ...(detail ? { detail } : {}) })
    if (!entry) problem('not built')
    else if (sha256(readSource(recipe.source)) !== entry.source) problem('source changed')
    else if (recipeHash(recipe) !== entry.recipe) problem('recipe changed')
    else {
      const missing = entry.outputs.find((o) => !io.exists(o))
      const changed = missing ? undefined : entry.outputs.find((o) => {
        const named = NAME_HASH.exec(o)?.[1]
        return named !== undefined && contentHash(io.readOutput(o)) !== named
      })
      if (missing) problem('output missing', missing)
      else if (changed) problem('output changed', changed)
    }
  }
  return problems
}

/**
 * The checks over the whole tree (only meaningful with every recipe): the committed manifest is
 * exactly what the lock generates, and `public/assets` holds nothing the lock did not produce.
 */
export function checkTree(recipes: readonly Recipe[], lock: Lock, io: CheckIo = diskIo): LockProblem[] {
  const problems: LockProblem[] = []
  // git may check the file out with CRLF on Windows; the content is what counts
  if (io.manifest().replace(/\r\n/g, '\n') !== manifestSource(recipes, lock)) problems.push({ id: relative(WEB_ROOT, MANIFEST_FILE).split(sep).join('/'), problem: 'manifest stale' })
  const locked = new Set(Object.values(lock).flatMap((e) => e.outputs))
  for (const file of io.publicAssets().sort()) if (!locked.has(file)) problems.push({ id: file, problem: 'orphan' })
  return problems
}
